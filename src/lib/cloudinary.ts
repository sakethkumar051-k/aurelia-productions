import type { MediaAsset } from '@/content/schema';

export const CLOUD_NAME = process.env.NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME ?? '';

export function isCloudinaryConfigured(): boolean {
  return CLOUD_NAME.length > 0;
}

/**
 * `next/image` loader for Cloudinary.
 *
 * `f_auto` and `q_auto` let Cloudinary pick format and quality per browser, so
 * the delivered bytes are AVIF/WebP where supported without us managing
 * variants. Transformations happen on Cloudinary's CDN, not our server — which
 * is the point of using it rather than Next's own optimiser.
 */
export function cloudinaryLoader({
  src,
  width,
  quality,
}: {
  src: string;
  width: number;
  quality?: number;
}): string {
  const transforms = [
    'f_auto',
    `q_${quality ?? 'auto'}`,
    `w_${width}`,
    'c_limit',
  ].join(',');

  const separator = src.startsWith('c_crop,') ? src.indexOf('/') : -1;
  const crop = separator >= 0 ? `${src.slice(0, separator)}/` : '';
  const publicId = separator >= 0 ? src.slice(separator + 1) : src;
  return `https://res.cloudinary.com/${CLOUD_NAME}/image/upload/${crop}${transforms}/${publicId}`;
}

/** A tiny blurred placeholder, generated by Cloudinary from the same asset. */
export function blurUrl(publicId: string): string {
  return cloudinaryLoader({ src: publicId, width: 24 }).replace('c_limit/', 'c_limit,e_blur:200/');
}

/** Keep the original intact; crop before generating responsive image sizes. */
export function assetSource(asset: MediaAsset): string {
  const crop = asset.crop;
  return crop
    ? `c_crop,x_${crop.x},y_${crop.y},w_${crop.width},h_${crop.height}/${asset.publicId}`
    : asset.publicId;
}

export function assetUrl(asset: MediaAsset, width = 1600): string {
  return cloudinaryLoader({ src: assetSource(asset), width });
}
